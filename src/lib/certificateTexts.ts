export type CertificateTexts = Record<string, string>
export const defaultCertificateTexts: CertificateTexts = Object.fromEntries(CERTIFICATE_TEXT_FIELDS.map(field => [field.key, field.defaultValue]))
export function certificateText(original: string, values: CertificateTexts = {}) {
  const field = CERTIFICATE_TEXT_FIELDS.find(field => field.defaultValue === original)
  return field ? (values[field.key] ?? field.defaultValue) : original
}
export function validateCertificateTexts(input: unknown): CertificateTexts {
  if (!input || typeof input !== "object" || Array.isArray(input)) throw new Error("ข้อมูลข้อความไม่ถูกต้อง")
  const result: CertificateTexts = {}
  for (const field of CERTIFICATE_TEXT_FIELDS) {
    const value = (input as Record<string, unknown>)[field.key]
    if (value === undefined) continue
    if (typeof value !== "string" || value.length > field.maxLength || /[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(value)) throw new Error(`ข้อความ ${field.label} ไม่ถูกต้อง หรือยาวเกิน ${field.maxLength} ตัวอักษร`)
    result[field.key] = value
  }
  return result
}
